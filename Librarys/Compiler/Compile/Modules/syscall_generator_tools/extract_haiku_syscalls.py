#!/usr/bin/env python3
"""
extract_haiku_syscalls.py

Read the real syscall numbers out of a Haiku x86_64 libroot.so and write
haiku_syscall_numbers.py. Each _kern_* stub in libroot is
    [mov %rcx,%r10]  mov $N,%rax  syscall  ret
so N is authoritative for that Haiku build. Haiku assigns numbers by the
order of headers/private/system/syscalls.h, so they drift between builds;
re-run this against the target's libroot whenever the target changes.

Usage:
    python3 extract_haiku_syscalls.py /path/to/libroot.so [-o haiku_syscall_numbers.py]
        [--ailang ../../../../Haiku/Library.HaikuNr.ailang]

Needs binutils objdump on the host.

Copyright (c) 2026 Sean Collins, 2 Paws Machine and Engineering. All rights reserved.
Licensed under the Sean Collins Software License (SCSL).
"""

import argparse
import re
import subprocess
import sys

STUB_RE = re.compile(r"^[0-9a-f]+ <(_kern_[A-Za-z0-9_]+)>:$")
MOV_RE = re.compile(r"\bmov\s+\$0x([0-9a-f]+),%[re]ax\b")


def extract(libroot):
    out = subprocess.run(
        ["objdump", "-d", "--no-show-raw-insn", libroot],
        check=True, capture_output=True, text=True,
    ).stdout
    nums = {}
    current = None
    for line in out.splitlines():
        m = STUB_RE.match(line.strip())
        if m:
            current = m.group(1)
            continue
        if current is None:
            continue
        if "syscall" in line.split():
            current = None
            continue
        m = MOV_RE.search(line)
        if m:
            nums[current] = int(m.group(1), 16)
            current = None
    return nums


def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("libroot")
    ap.add_argument("-o", "--output", default="haiku_syscall_numbers.py")
    ap.add_argument("--ailang", help="also write the numbers as FixedPool.HaikuNr")
    args = ap.parse_args()

    nums = extract(args.libroot)
    if not nums:
        sys.exit("no _kern_* stubs found in " + args.libroot)

    with open(args.output, "w") as f:
        f.write('"""Haiku syscall numbers extracted from libroot.so by '
                'extract_haiku_syscalls.py. Do not edit."""\n\n')
        f.write("HAIKU_SYSCALL_NUMBERS = {\n")
        for name, n in sorted(nums.items(), key=lambda kv: kv[1]):
            f.write(f'    "{name}": {n},\n')
        f.write("}\n")
    print(f"{len(nums)} syscalls -> {args.output}")

    if args.ailang:
        with open(args.ailang, "w") as f:
            f.write("// Library.HaikuNr.ailang - Haiku x86_64 syscall numbers\n"
                    "// GENERATED by Librarys/Compiler/Compile/Modules/syscall_generator_tools/"
                    "extract_haiku_syscalls.py\n"
                    "// from the target's libroot.so. DO NOT EDIT; re-extract when the target changes.\n"
                    "//\n"
                    "// Copyright (c) 2026 Sean Collins, 2 Paws Machine and Engineering. All rights reserved.\n"
                    "// Licensed under the Sean Collins Software License (SCSL v1.0).\n\n"
                    "FixedPool.HaikuNr {\n")
            for name, n in sorted(nums.items(), key=lambda kv: kv[1]):
                f.write(f'    "{name[len("_kern_"):].upper()}": Initialize={n}\n')
            f.write("}\n")
        print(f"{len(nums)} syscalls -> {args.ailang}")


if __name__ == "__main__":
    main()
